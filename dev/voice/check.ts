// [voice] Voice check: `node dev/voice/check.ts [flags]` — runs every speech fixture through the REAL recogniser in a
// browser and gates accuracy, false positives and latency. Results: dev/voice/out/<run>.json + a printed report.
//
// Flags:
//   --fast              fake mic feed, faster than real time (same commands as real mode, no latency numbers)
//   --engine webkit     WebKit instead of Chromium (report only, not gated)
//   --prod              production build under /sing/: (1) startPreview() main app smoke (lazy chunk, voice ready),
//                       (2) a production build that also contains dev/voice/index.html, fixtures run against it
//   --filter <s>        only fixtures whose file name contains s (comma = any of)
//   --pages <n>         parallel pages (default 3 real, 1 fast; each page has its own vosk worker and model copy)
//   --release <sec>     end() this long after the speech ends (default 0.3)
//   --speedup <x>       fast mode pace (default 8 × real time)
//   --tag <name>        suffix for the results file name
//   --no-gate           report only
// Fixtures: dev/fixtures/out/speech/ (generated by dev/voice/make-speech.ts when missing).
// Profile: dev/voice/out/profile-<engine>. vosk keys its IndexedDB cache by the FULL model URL, port included, so
// the cache only carries over between runs when PORT is pinned (env); otherwise the profile is wiped at start (no
// 71 MB copy per run). Either way page 1 of a run measures a cold load (download + unpack + IndexedDB write) unless
// PORT is pinned and the model is cached, and pages 2+ measure warm loads (IndexedDB → wasm).
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { chromium, webkit, type BrowserContext, type Page } from '@playwright/test';
import { build, preview } from 'vite';
import type { Command } from '../../src/types.ts';
import { freePort, startDev, startPreview, type Served } from '../lib/serve.ts';
import { MANIFEST_PATH, SPEECH_DIR, makeSpeech, type SpeechFixture, type SpeechManifest } from './make-speech.ts';
import type { HoldReport, LoadReport, VoicePage } from './page.ts';

const ROOT = join(import.meta.dirname, '..', '..');
const OUT_DIR = join(import.meta.dirname, 'out');
const FIXTURE_ROUTE = '__fixtures/';
/** holdStart fires this long after touch-down (ui/input.ts DEFAULT_HOLD_MS) */
const HOLD_DELAY_SEC = 0.3;
const BOOT_TIMEOUT_MS = 30_000;
const LOAD_TIMEOUT_MS = 180_000;

// gate
const GATE_CLEAN = 0.9;
const GATE_NOISY = 0.8;
const GATE_RELEASE_MEDIAN_SEC = 0.4;

type Engine = 'chromium' | 'webkit';
type W = { __voice: VoicePage };

interface Args {
  fast: boolean;
  engine: Engine;
  prod: boolean;
  filter: string[];
  pages: number;
  release: number;
  speedup: number;
  gate: boolean;
  tag: string;
}

function parseArgs(argv: string[]): Args {
  const a: Args = { fast: false, engine: 'chromium', prod: false, filter: [], pages: 0, release: 0.3, speedup: 8, gate: true, tag: '' };
  for (let i = 0; i < argv.length; i++) {
    const k = argv[i];
    if (k === '--fast') a.fast = true;
    else if (k === '--prod') a.prod = true;
    else if (k === '--no-gate') a.gate = false;
    else if (k === '--engine') a.engine = argv[++i] as Engine;
    else if (k === '--filter') a.filter = argv[++i].split(',');
    else if (k === '--pages') a.pages = Number(argv[++i]);
    else if (k === '--release') a.release = Number(argv[++i]);
    else if (k === '--speedup') a.speedup = Number(argv[++i]);
    else if (k === '--tag') a.tag = argv[++i];
    else throw new Error(`unknown flag ${k}`);
  }
  a.pages ||= a.fast ? 1 : 3;
  return a;
}

// ---------- browser ----------

async function openContext(engine: Engine, profileDir: string): Promise<BrowserContext> {
  mkdirSync(profileDir, { recursive: true });
  const ctx = engine === 'webkit'
    ? await webkit.launchPersistentContext(profileDir, { headless: true })
    : await chromium.launchPersistentContext(profileDir, { headless: true, args: ['--autoplay-policy=no-user-gesture-required'] });
  await ctx.route(`**/${FIXTURE_ROUTE}**`, (route) => {
    const file = decodeURIComponent(basename(new URL(route.request().url()).pathname));
    return route.fulfill({ path: join(SPEECH_DIR, file), contentType: 'audio/wav' });
  });
  return ctx;
}

async function bootPage(ctx: BrowserContext, pageUrl: string, errors: string[]): Promise<Page> {
  const page = await ctx.newPage();
  page.on('console', (m) => {
    if (m.type() === 'error' || m.type() === 'warning') errors.push(`[${m.type()}] ${m.text()}`);
  });
  page.on('pageerror', (e) => errors.push(`[pageerror] ${e.message}`));
  await page.goto(pageUrl);
  await page.click('#start');
  await page.waitForFunction(() => (window as unknown as W).__voice?.booted || (window as unknown as W).__voice?.error, null, { timeout: BOOT_TIMEOUT_MS });
  const err = await page.evaluate(() => (window as unknown as W).__voice.error);
  if (err) throw new Error(`page boot failed: ${err}`);
  return page;
}

async function loadModel(page: Page): Promise<LoadReport> {
  page.setDefaultTimeout(LOAD_TIMEOUT_MS);
  return page.evaluate(() => (window as unknown as W).__voice.load());
}

/** RSS (MB) of every process of the browser started with this profile dir (browser + renderers + GPU …) */
function browserRssMb(profileDir: string): number | null {
  try {
    const rows = execFileSync('ps', ['-A', '-o', 'pid=,ppid=,rss=,command='], { encoding: 'utf8', maxBuffer: 64 << 20 })
      .split('\n').map((l) => /^\s*(\d+)\s+(\d+)\s+(\d+)\s+(.*)$/.exec(l)).filter((m) => !!m)
      .map((m) => ({ pid: +m[1], ppid: +m[2], rss: +m[3], cmd: m[4] }));
    const roots = rows.filter((r) => r.cmd.includes(profileDir) && !rows.some((p) => p.pid === r.ppid && p.cmd.includes(profileDir)));
    const tree = new Set(roots.map((r) => r.pid));
    for (let grew = true; grew; ) {
      grew = false;
      for (const r of rows) if (!tree.has(r.pid) && tree.has(r.ppid)) (tree.add(r.pid), (grew = true));
    }
    const kb = rows.filter((r) => tree.has(r.pid)).reduce((s, r) => s + r.rss, 0);
    return tree.size ? Math.round(kb / 1024) : null;
  } catch {
    return null;
  }
}

// ---------- fixtures ----------

interface Row {
  fx: SpeechFixture;
  rep: HoldReport | null;
  error: string | null;
}

const sameCommand = (a: Command | null, b: Command | null) => JSON.stringify(a) === JSON.stringify(b);
const isCorrect = (r: Row) => !!r.rep && sameCommand(r.rep.command, r.fx.command) && r.rep.fireCount === (r.fx.command ? 1 : 0) && sameCommand(r.rep.fired, r.fx.command);

function loadManifest(): SpeechManifest {
  return JSON.parse(readFileSync(MANIFEST_PATH, 'utf8')) as SpeechManifest;
}

async function runFixtures(pages: Page[], fixtures: SpeechFixture[], base: string, release: number): Promise<Row[]> {
  const rows: Row[] = [];
  let next = 0;
  let done = 0;
  const worker = async (page: Page) => {
    while (next < fixtures.length) {
      const fx = fixtures[next++];
      const o = { url: `${base}${FIXTURE_ROUTE}${encodeURIComponent(fx.file)}`, speechEnd: fx.speechEnd, holdDelaySec: HOLD_DELAY_SEC, releaseAfterSec: release };
      try {
        const rep = await page.evaluate((opts) => (window as unknown as W).__voice.hold(opts), o);
        rows.push({ fx, rep, error: null });
      } catch (e) {
        rows.push({ fx, rep: null, error: e instanceof Error ? e.message : String(e) });
      }
      if (++done % 50 === 0) console.log(`  … ${done}/${fixtures.length}`);
    }
  };
  await Promise.all(pages.map(worker));
  return rows.sort((p, q) => p.fx.file.localeCompare(q.fx.file));
}

// ---------- report ----------

const pct = (n: number, d: number) => (d ? `${((100 * n) / d).toFixed(1)}%` : '—');
const ms = (s: number | null | undefined) => (s === null || s === undefined ? '—' : `${Math.round(s * 1000)} ms`);

function quantile(xs: number[], q: number): number | null {
  if (!xs.length) return null;
  const s = [...xs].sort((a, b) => a - b);
  return s[Math.min(s.length - 1, Math.floor(q * (s.length - 1) + 0.5))];
}

interface Summary {
  clean: { ok: number; n: number };
  noisy: { ok: number; n: number };
  wrongCommand: number;
  falsePositives: Row[];
  negatives: number;
  /** max(0, onCommand − release) for correct commands */
  releaseToCommand: number[];
  firedEarly: number;
  firedAfterSpeechEnd: number[];
  endResolve: number[];
  doubleFires: number;
}

function summarise(rows: Row[]): Summary {
  const cmd = rows.filter((r) => r.fx.kind === 'command');
  const neg = rows.filter((r) => r.fx.kind === 'negative');
  const count = (noisy: boolean) => {
    const g = cmd.filter((r) => r.fx.noisy === noisy);
    return { ok: g.filter(isCorrect).length, n: g.length };
  };
  const correct = cmd.filter(isCorrect);
  const timed = correct.filter((r) => r.rep!.firedAfterRelease !== null);
  return {
    clean: count(false),
    noisy: count(true),
    wrongCommand: cmd.filter((r) => r.rep?.command && !sameCommand(r.rep.command, r.fx.command)).length,
    falsePositives: neg.filter((r) => !r.rep || r.rep.command || r.rep.fireCount > 0),
    negatives: neg.length,
    releaseToCommand: timed.map((r) => Math.max(0, r.rep!.firedAfterRelease!)),
    firedEarly: timed.filter((r) => r.rep!.firedAfterRelease! < 0).length,
    firedAfterSpeechEnd: timed.map((r) => r.rep!.firedAfterSpeechEnd!),
    endResolve: rows.map((r) => r.rep?.endResolveSec).filter((x): x is number => typeof x === 'number'),
    doubleFires: rows.filter((r) => (r.rep?.fireCount ?? 0) > 1).length,
  };
}

function printAccuracyTable(rows: Row[]): void {
  const cmd = rows.filter((r) => r.fx.kind === 'command');
  const voices = [...new Set(cmd.map((r) => r.fx.voice))];
  const rates = [...new Set(cmd.map((r) => r.fx.rateWpm))].sort();
  const cols = rates.flatMap((rate) => [false, true].map((noisy) => ({ rate, noisy })));
  console.log(`\n  ${'voice'.padEnd(10)}${cols.map((c) => `${c.rate}${c.noisy ? ' noisy' : ' clean'}`.padStart(14)).join('')}`);
  for (const v of voices) {
    const cells = cols.map((c) => {
      const g = cmd.filter((r) => r.fx.voice === v && r.fx.rateWpm === c.rate && r.fx.noisy === c.noisy);
      return `${g.filter(isCorrect).length}/${g.length}`.padStart(14);
    });
    console.log(`  ${v.padEnd(10)}${cells.join('')}`);
  }
}

function printMisses(rows: Row[]): void {
  const bad = rows.filter((r) => !isCorrect(r));
  if (!bad.length) return;
  console.log(`\n  misses / false positives (${bad.length}):`);
  for (const r of bad) {
    const last = r.rep?.partials.at(-1)?.text ?? '';
    const got = r.error ? `ERROR ${r.error}` : `${JSON.stringify(r.rep!.command)} fired×${r.rep!.fireCount} heard "${last}"`;
    console.log(`    ${r.fx.file.padEnd(48)} want ${JSON.stringify(r.fx.command)} got ${got}`);
  }
}

function printSummary(s: Summary, fast: boolean): void {
  console.log(`\n  clean ${s.clean.ok}/${s.clean.n} = ${pct(s.clean.ok, s.clean.n)} · noisy ${s.noisy.ok}/${s.noisy.n} = ${pct(s.noisy.ok, s.noisy.n)} · wrong command ${s.wrongCommand} · double fires ${s.doubleFires}`);
  console.log(`  false positives ${s.falsePositives.length}/${s.negatives}${s.falsePositives.length ? ': ' + s.falsePositives.map((r) => r.fx.file).join(', ') : ''}`);
  if (fast) return;
  const n = s.releaseToCommand.length;
  console.log(`  release→command: median ${ms(quantile(s.releaseToCommand, 0.5))}, p95 ${ms(quantile(s.releaseToCommand, 0.95))} · fired before release ${s.firedEarly}/${n} (${pct(s.firedEarly, n)})`);
  console.log(`  command after speech end: median ${ms(quantile(s.firedAfterSpeechEnd, 0.5))}, p95 ${ms(quantile(s.firedAfterSpeechEnd, 0.95))}`);
  console.log(`  end() resolve: median ${ms(quantile(s.endResolve, 0.5))}, p95 ${ms(quantile(s.endResolve, 0.95))}`);
}

function gateFailures(s: Summary, fast: boolean): string[] {
  const f: string[] = [];
  if (s.clean.n && s.clean.ok / s.clean.n < GATE_CLEAN) f.push(`clean ${pct(s.clean.ok, s.clean.n)} < ${GATE_CLEAN * 100}%`);
  if (s.noisy.n && s.noisy.ok / s.noisy.n < GATE_NOISY) f.push(`noisy ${pct(s.noisy.ok, s.noisy.n)} < ${GATE_NOISY * 100}%`);
  if (s.falsePositives.length) f.push(`${s.falsePositives.length} false positives`);
  if (s.doubleFires) f.push(`${s.doubleFires} holds fired more than once`);
  const med = quantile(s.releaseToCommand, 0.5);
  if (!fast && med !== null && med > GATE_RELEASE_MEDIAN_SEC) f.push(`release→command median ${ms(med)} > ${ms(GATE_RELEASE_MEDIAN_SEC)}`);
  return f;
}

// ---------- servers ----------

/** production build that also contains the dev page (same vite.config.ts; extra input; separate outDir) */
async function startProdWithDevPage(): Promise<Served> {
  const outDir = join(OUT_DIR, 'dist');
  await build({
    root: ROOT, logLevel: 'warn',
    build: { outDir, emptyOutDir: true, rollupOptions: { input: { main: join(ROOT, 'index.html'), voice: join(ROOT, 'dev/voice/index.html') } } },
  });
  const port = Number(process.env.PORT) || (await freePort());
  const server = await preview({ root: ROOT, logLevel: 'warn', build: { outDir }, preview: { port, strictPort: true, host: '127.0.0.1' } });
  return { url: `http://127.0.0.1:${port}/sing/`, close: () => new Promise<void>((r) => server.httpServer.close(() => r())) };
}

interface ProdSmoke {
  mainChunkKb: number;
  voskChunkKb: number;
  voskInMainChunk: boolean;
  voiceStatus: string;
  loadMs: number;
  errors: string[];
}

/** the real app from startPreview(): vosk is a separate lazy chunk and voice reaches 'ready' with ?test&voice */
async function prodSmoke(engine: Engine): Promise<ProdSmoke> {
  const served = await startPreview(ROOT);
  const errors: string[] = [];
  try {
    const assets = join(ROOT, 'dist', 'assets');
    const js = readdirSync(assets).filter((f) => f.endsWith('.js')).map((f) => ({ f, kb: Math.round(statSync(join(assets, f)).size / 1024), src: readFileSync(join(assets, f), 'utf8') }));
    const html = readFileSync(join(ROOT, 'dist', 'index.html'), 'utf8');
    const main = js.find((x) => html.includes(x.f))!;
    const vosk = js.find((x) => x.src.includes('KaldiRecognizer'))!;
    const ctx = await openContext(engine, join(OUT_DIR, `profile-${engine}`));
    try {
      const page = await ctx.newPage();
      page.on('console', (m) => (m.type() === 'error' || m.type() === 'warning') && errors.push(`[${m.type()}] ${m.text()}`));
      await page.goto(`${served.url}?test&voice`);
      const t0 = Date.now();
      await page.dispatchEvent('.start', 'pointerup');
      await page.waitForSelector('[aria-label="Settings"]', { timeout: BOOT_TIMEOUT_MS });
      await page.click('[aria-label="Settings"]');
      const status = await page.waitForFunction(() => /voice (ready|error|off)/.exec(document.body.innerText)?.[1], null, { timeout: LOAD_TIMEOUT_MS, polling: 250 });
      return { mainChunkKb: main.kb, voskChunkKb: vosk.kb, voskInMainChunk: main === vosk, voiceStatus: String(await status.jsonValue()), loadMs: Date.now() - t0, errors };
    } finally {
      await ctx.close();
    }
  } finally {
    await served.close();
  }
}

// ---------- main ----------

async function main(): Promise<void> {
  const args = parseArgs(process.argv.slice(2));
  if (!existsSync(join(ROOT, 'public', 'vosk', 'vosk-model-small-en-us-0.15.tar.gz'))) throw new Error('model missing: run npm run fetch-model');
  if (!existsSync(MANIFEST_PATH)) {
    console.log('generating speech fixtures …');
    await makeSpeech();
  }
  mkdirSync(OUT_DIR, { recursive: true });
  const runName = `${args.engine}-${args.prod ? 'prod' : 'dev'}-${args.fast ? 'fast' : 'real'}${args.tag ? `-${args.tag}` : ''}`;
  const all = loadManifest().fixtures;
  const fixtures = args.filter.length ? all.filter((f) => args.filter.some((s) => f.file.includes(s))) : all;
  console.log(`voice check ${runName}: ${fixtures.length} fixtures, release +${args.release} s${args.fast ? `, fast ×${args.speedup}` : ''}, ${args.pages} page(s)`);

  const report: Record<string, unknown> = { runName, args, at: new Date().toISOString() };
  if (args.prod) {
    report.prodSmoke = await prodSmoke(args.engine);
    console.log('  prod smoke (startPreview, main app ?test&voice):', report.prodSmoke);
  }
  const served = args.prod ? await startProdWithDevPage() : await startDev(ROOT);
  const pageUrl = `${served.url}dev/voice/index.html${args.fast ? `?fast&speedup=${args.speedup}` : ''}`;
  const errors: string[] = [];
  try {
    const profileDir = join(OUT_DIR, `profile-${args.engine}`);
    if (!process.env.PORT) rmSync(profileDir, { recursive: true, force: true }); // see the header: cache key has the port
    const ctx = await openContext(args.engine, profileDir);
    try {
      const pages: Page[] = [];
      const loads: (LoadReport & { downloaded: boolean; rssBeforeMb: number | null; rssAfterMb: number | null })[] = [];
      for (let i = 0; i < args.pages; i++) {
        const p = await bootPage(ctx, pageUrl, errors);
        const rssBeforeMb = browserRssMb(profileDir);
        const l = await loadModel(p);
        if (l.status !== 'ready') throw new Error(`model did not load: ${l.error ?? l.status}\n${errors.join('\n')}`);
        // a download reports byte progress; a cached load goes 0 → 1
        loads.push({ ...l, downloaded: l.progress.length > 2, rssBeforeMb, rssAfterMb: browserRssMb(profileDir) });
        pages.push(p);
      }
      for (const l of loads) {
        const steps = l.downloaded ? `, progress ${l.progress.length} steps: ${JSON.stringify(l.progress.slice(0, 2))} … ${JSON.stringify(l.progress.slice(-2))}` : '';
        console.log(`  model load: ${l.ms} ms ${l.downloaded ? 'COLD (downloaded)' : 'WARM (IndexedDB)'} · RSS ${l.rssBeforeMb} → ${l.rssAfterMb} MB${steps}`);
      }
      const rssBefore = loads[0].rssBeforeMb;
      const rssLoaded = loads.at(-1)!.rssAfterMb;
      const nPages = pages.length;
      const t0 = Date.now();
      const rows = await runFixtures(pages, fixtures, served.url, args.release);
      const rssAfter = browserRssMb(profileDir);
      const heap = await pages[0].evaluate(() => (window as unknown as W).__voice.jsHeap());
      console.log(`  ran ${rows.length} fixtures in ${((Date.now() - t0) / 1000).toFixed(1)} s · RSS after ${rssAfter} MB · main-thread JS heap ${heap === null ? '—' : `${(heap / 1048576).toFixed(1)} MB`}`);
      const s = summarise(rows);
      printAccuracyTable(rows);
      printMisses(rows);
      printSummary(s, args.fast);
      Object.assign(report, { loads, rss: { before: rssBefore, loaded: rssLoaded, after: rssAfter, pages: nPages }, jsHeap: heap, summary: { ...s, falsePositives: s.falsePositives.map((r) => r.fx.file) }, rows, errors });
      const fails = gateFailures(s, args.fast);
      if (errors.length) console.log(`\n  console errors/warnings (${errors.length}):\n    ${[...new Set(errors)].slice(0, 15).join('\n    ')}`);
      writeFileSync(join(OUT_DIR, `${runName}.json`), JSON.stringify(report, null, 1));
      console.log(`\n  results → ${join(OUT_DIR, `${runName}.json`)}`);
      if (args.gate && args.engine === 'chromium') {
        console.log(fails.length ? `\nFAIL ${fails.join(' · ')}` : '\nPASS gate');
        if (fails.length) process.exitCode = 1;
      }
    } finally {
      await ctx.close();
    }
  } finally {
    await served.close();
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
